let idioma_atual = 'en';

function _detectar_idioma() {
    try {
        const valor = localStorage.getItem('dadinho_idioma');
        if (valor && I18N_DICIONARIOS[valor]) {
            return valor;
        }
    } catch (erro) {
        // localStorage indisponível: segue para o idioma do navegador.
    }
    const nav = String((typeof navigator !== 'undefined' && navigator.language) || 'en').toLowerCase();
    if (nav.indexOf('pt') === 0) {
        return 'pt-BR';
    }
    if (nav.indexOf('es') === 0) {
        return 'es';
    }
    if (nav.indexOf('fr') === 0) {
        return 'fr';
    }
    if (nav.indexOf('zh') === 0) {
        return 'zh-CN';
    }
    return 'en';
}

function _resolver_face(valor, quantidade) {
    const n = parseInt(valor, 10);
    if (!(n >= 1 && n <= 6)) {
        return valor;
    }
    const chave = `face.${n}.${Number(quantidade) > 1 ? 'plural' : 'singular'}`;
    return t(chave);
}

// Substitui {param} mantendo o marcador quando o valor não veio.
function _interpolar(texto, params) {
    if (!params || !texto) {
        return texto;
    }
    return texto.replace(/\{(\w+)\}/g, function (marcador, chave) {
        if (params[chave] === undefined || params[chave] === null) {
            return marcador;
        }
        return String(params[chave]);
    });
}

function _com_faces(params) {
    if (!params) {
        return params;
    }
    const resolvidos = Object.assign({}, params);
    if (resolvidos.face !== undefined && resolvidos.qtd !== undefined) {
        resolvidos.face = _resolver_face(resolvidos.face, resolvidos.qtd);
    }
    if (resolvidos.face_ant !== undefined && resolvidos.qtd_ant !== undefined) {
        resolvidos.face_ant = _resolver_face(resolvidos.face_ant, resolvidos.qtd_ant);
    }
    return resolvidos;
}

function t(chave, params) {
    const dic = I18N_DICIONARIOS[idioma_atual] || {};
    const base = I18N_DICIONARIOS.en || {};
    let texto = dic[chave];
    if (texto === undefined) {
        texto = base[chave];
    }
    if (texto === undefined) {
        return chave;
    }
    return _interpolar(texto, _com_faces(params));
}

// Lista de traduções (ex.: dicas). Cai para o inglês se faltar.
function t_list(chave) {
    const dic = I18N_DICIONARIOS[idioma_atual] || {};
    const base = I18N_DICIONARIOS.en || {};
    const valor = dic[chave] !== undefined ? dic[chave] : base[chave];
    return Array.isArray(valor) ? valor : [];
}

// Narração vinda do servidor: concatena os segmentos traduzidos. Se o payload
// não trouxer segmentos, usa o texto pt-BR de fallback.
function traduzirSegmentos(segmentos, textoFallback) {
    if (!Array.isArray(segmentos) || segmentos.length === 0) {
        return textoFallback || '';
    }
    return segmentos.map(function (segmento) {
        if (!segmento || !segmento.chave) {
            return '';
        }
        return t(segmento.chave, segmento.params || {});
    }).join('');
}

// Aplica as traduções em um subárvore do DOM (padrão: documento inteiro).
function aplicar_traducoes(raiz) {
    const escopo = raiz || document;
    escopo.querySelectorAll('[data-i18n]').forEach(function (el) {
        el.textContent = t(el.getAttribute('data-i18n'));
    });
    escopo.querySelectorAll('[data-i18n-html]').forEach(function (el) {
        el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    escopo.querySelectorAll('[data-i18n-title]').forEach(function (el) {
        el.title = t(el.getAttribute('data-i18n-title'));
    });
    escopo.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
        el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });
    escopo.querySelectorAll('[data-i18n-value]').forEach(function (el) {
        el.value = t(el.getAttribute('data-i18n-value'));
    });
    escopo.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) {
        el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
    });
}

// Troca o idioma atual e atualiza a tela. Recarrega a página para que os
// conteúdos dinâmicos (já renderizados) apareçam no novo idioma.
function definir_idioma(codigo) {
    if (!I18N_DICIONARIOS[codigo]) {
        codigo = 'en';
    }
    try {
        localStorage.setItem('dadinho_idioma', codigo);
    } catch (erro) {
        // sem persistência: idioma vale só para esta sessão.
    }
    idioma_atual = codigo;
    document.documentElement.lang = codigo;
    window.location.reload();
}

function _montar_seletor_idioma() {
    const seletor = document.getElementById('seletor_idioma');
    if (!seletor) {
        return;
    }
    seletor.innerHTML = '';
    I18N_IDIOMAS.forEach(function (idioma) {
        const opcao = document.createElement('option');
        opcao.value = idioma.codigo;
        opcao.textContent = idioma.nome;
        if (idioma.codigo === idioma_atual) {
            opcao.selected = true;
        }
        seletor.appendChild(opcao);
    });
    seletor.setAttribute('aria-label', t('ui.seletor_idioma'));
    seletor.title = t('ui.seletor_idioma');
    seletor.addEventListener('change', function () {
        definir_idioma(seletor.value);
    });
}

function iniciar_i18n() {
    idioma_atual = _detectar_idioma();
    document.documentElement.lang = idioma_atual;
    document.title = t('ui.titulo_documento');
    aplicar_traducoes(document);
    _montar_seletor_idioma();
}

