// (carregado em seguida) monta os textos dinâmicos.
if (document.getElementById('seletor_idioma') || document.readyState !== 'loading') {
    iniciar_i18n();
} else {
    document.addEventListener('DOMContentLoaded', iniciar_i18n);
}
